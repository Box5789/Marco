"""Compile declared Korean tax knowledge to a native MARCO graph and .mco.

This is explicit knowledge authoring/compilation, not neural weight training.
No examples from the held-out evaluator are read here.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from marco.knowledge.korean_tax import knowledge


def build():
    pack = knowledge()
    by_source = {s['id']: s for s in pack['sources']}
    goal = '검증된세법설명'
    lines = ['# Generated by tools/build_korean_tax_pack.py. Do not hand edit.',
             '# Explicitly selected training/evaluation asset, not a standalone tax calculator.',
             '역할: 한국 세법 제한 지식', '목표: '+goal, '언어: 한국어', '이름말: 문장',
             '임계값: 0.80 / 0.90', '전진관계: 확인함, 이어짐', '부정관계: 막힘', '근거관계: 확인함',
             '[개념]', goal+': "검증된 세법 설명"']
    for fact in pack['facts']:
        name=fact['id'].replace('-','_')
        source=by_source[fact['source_ids'][0]]
        # Only source title in KG syntax: colon is the node delimiter.
        text='2026-01-02부터 2026-11-06까지 확인한 제한 지식입니다. '+fact['answer']
        lines.append(f'{name} @{source["title"]}: '+json.dumps(text,ensure_ascii=False))
    lines += ['[사례]']
    for fact in pack['facts']:
        name=fact['id'].replace('-','_')
        lines.append('*질문_'+name+': '+' | '.join(json.dumps(q.rstrip('?'),ensure_ascii=False) for q in fact['questions']))
    lines += ['[무관]', '_범위밖: "개인별 확정 납부세액을 알려줘" | "부동산 양도세를 확정해" | "미래 세법을 예측해"', '[논증]']
    for fact in pack['facts']:
        name=fact['id'].replace('-','_')
        lines += [f'질문_{name} -확인함-> {name}', f'{name} -이어짐-> {goal}']
    lines += ['[대사]', '인정: {claim}',
              '인정_반격: {claim} 추가 조건을 별도로 확인해야 합니다.',
              'B2: 검증된 세법 지식 범위 밖입니다.', 'B2_강등: 검증된 세법 지식 범위 밖입니다.',
              'A: 질문을 특정하지 못했습니다. 세목과 기준일을 확인해 주세요.',
              '근거없음: 이 주장을 뒷받침할 확인된 근거가 없습니다.',
              'C: 이 자료만으로는 판단할 수 없습니다.', 'B1: 확인된 근거가 부족합니다.',
              '미지: 확인된 근거가 부족합니다.', '남은요건:', '요건충족:']
    graph=ROOT/'legal/graph_한국세법_2026.kg'
    graph.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    import engine
    engine.verify(engine.read_kg(str(graph)))
    import mco
    output=ROOT/'models/MARCO-Korean-Tax-Core-2026.mco'
    report=mco.compile(ROOT, output, name=pack['pack_id'], build_id=pack['verified_through'],
                       graphs=['legal/graph_한국세법_2026.kg'], language='styles/한국어.json', format='native')
    return {'graph':str(graph),'model':str(output),'sha256':report.sha256,'size_bytes':report.size_bytes}


if __name__ == '__main__':
    print(json.dumps(build(),ensure_ascii=False))
